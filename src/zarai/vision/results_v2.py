"""Build experiments/wheat_v2_results.md from the MLflow experiment wheat_v2.

Only measured numbers: anything not run is [TBD]. Dry runs are ignored, as are runs on any other
version of data/splits/wheat_v2.csv (by its DVC hash). Each cell is the mean ± SD over the seeds
run, taking the latest finished run per seed.
"""

import argparse
from collections import defaultdict
from pathlib import Path

import numpy as np

from zarai.common.config import load_config
from zarai.common.io import read_csv
from zarai.vision.data_v2 import available_folds
from zarai.vision.eval_external import _mean_sd
from zarai.vision.results import END, START, TBD, replace_section, table
from zarai.vision.tracking import dvc_hashes, set_tracking_uri

DOC = Path("experiments/wheat_v2_results.md")
INTRO = """# wheat_v2 results

Leave-one-source-out results for wheat_v2 (`data/splits/wheat_v2.csv`). Each model trains on all
but one source, selects its epoch and fits temperature and the abstention threshold on val from
those sources, and is then scored on the held-out source and on NWRD stripe rust tiles, which no
model ever trains or selects on. The tables below are generated by
`python -m zarai.vision.results_v2` (or `make results`) from MLflow; don't edit between the markers.

"""


def grid_combos(cfg) -> list[tuple[str, str, str, str]]:
    """(backbone, mode, aug, background) in grid order, skipping modes a backbone lacks."""
    return [
        (backbone, mode, aug, "none")
        for backbone in cfg.grid.backbones
        for mode in cfg.grid.modes
        if mode in cfg.backbones[backbone].modes
        for aug in cfg.grid.augs
    ]


def load_runs(cfg, splits_md5: str) -> list:
    import mlflow

    set_tracking_uri(cfg.mlflow.tracking_uri)
    if mlflow.get_experiment_by_name(cfg.mlflow.experiment) is None:
        return []
    found = mlflow.search_runs(
        experiment_names=[cfg.mlflow.experiment],
        output_format="list",
        filter_string="attributes.status = 'FINISHED' and tags.dry_run = 'false'",
        order_by=["attributes.start_time ASC"],
    )
    return [run for run in found if run.data.params.get("dvc.splits_md5") == splits_md5]


def latest_by_seed(runs) -> dict[tuple, dict[str, dict]]:
    """{(fold, backbone, mode, aug, background): {seed: metrics}}, latest run per seed."""
    grouped = defaultdict(dict)
    for run in runs:  # oldest first, so later runs replace earlier ones
        t = run.data.tags
        key = (t["fold"], t["backbone"], t["mode"], t["aug"], t.get("background", "none"))
        grouped[key][t["seed"]] = run.data.metrics
    return grouped


def _label(combo) -> list[str]:
    backbone, mode, aug, background = combo
    return [backbone, mode, aug + ("" if background == "none" else f", bg {background}")]


def _cell(seeds: dict[str, dict], key: str, digits: int = 4) -> str:
    return _mean_sd([m.get(key) for m in seeds.values()], digits) if seeds else TBD


def fold_classes(splits_csv) -> dict[str, list[str]]:
    rows = read_csv(splits_csv)
    classes = defaultdict(set)
    for row in rows:
        classes[row["source"]].add(row["label"])
    return {source: sorted(labels) for source, labels in classes.items()}


def _nanmean(values, digits: int) -> str:
    """Mean of the logged values, or TBD when none were logged."""
    found = [v for v in values if not np.isnan(v)]
    return f"{np.mean(found):.{digits}f}" if found else TBD


def render(cfg, grouped, folds, classes_by_source, dvc) -> list[str]:
    combos = grid_combos(cfg)
    extra = sorted({key[1:] for key in grouped} - set(combos))
    combos += extra
    n_seeds = len(cfg.grid.seeds)
    lines = [
        f"Dataset: splits `{dvc['dvc.splits_md5']}`, processed `{dvc['dvc.processed_md5']}`.",
        "",
        "Macro-F1 averages the classes present in the held-out set, and a prediction of any of the "
        "five classes counts. ECE is after temperature scaling. *Confidently wrong* is the share of "
        "all held-out images predicted wrongly with confidence at or above the val-fitted "
        "abstention threshold; *coverage* is the share answered at that threshold. NWRD has one "
        "class, so only its recall is shown. Mean ± SD over seeds; one seed shows no SD.",
        "",
    ]
    fold_means = defaultdict(dict)  # combo -> fold -> (macro-F1, NWRD recall, confidently wrong)
    for fold in folds:
        classes = classes_by_source.get(fold, [])
        lines += [f"## Held out: {fold}", ""]
        rows = []
        for combo in combos:
            seeds = grouped.get((fold, *combo), {})
            rows.append(
                [
                    *_label(combo),
                    f"{len(seeds)}/{n_seeds}",
                    _cell(seeds, "heldout_macro_f1"),
                    *[_cell(seeds, f"heldout_recall_{c}") for c in classes],
                    _cell(seeds, "nwrd_recall_yellow_rust"),
                    _cell(seeds, "heldout_ece"),
                    _cell(seeds, "heldout_confident_wrong", 3),
                    _cell(seeds, "heldout_coverage", 3),
                ]
            )
            values = [m.get("heldout_macro_f1") for m in seeds.values()]
            if seeds and None not in values:
                fold_means[combo][fold] = tuple(
                    float(np.mean([m.get(k, np.nan) for m in seeds.values()]))
                    for k in (
                        "heldout_macro_f1",
                        "nwrd_recall_yellow_rust",
                        "heldout_confident_wrong",
                    )
                )
        lines += table(
            [
                "backbone",
                "mode",
                "aug",
                "seeds",
                "macro-F1",
                *[f"recall {c}" for c in classes],
                "NWRD recall",
                "ECE",
                "confidently wrong",
                "coverage",
            ],
            rows,
        )
        lines.append("")

    lines += [
        "## Summary",
        "",
        "Ranked by the mean over folds of each fold's mean held-out macro-F1. Combinations missing "
        "a fold are ranked on the folds they have, so check the folds column.",
        "",
    ]
    ranked = sorted(fold_means, key=lambda c: -np.mean([v[0] for v in fold_means[c].values()]))
    summary = []
    for rank, combo in enumerate(ranked, 1):
        values = list(fold_means[combo].values())
        worst = min(fold_means[combo], key=lambda f: fold_means[combo][f][0])
        summary.append(
            [
                rank,
                *_label(combo),
                f"{len(values)}/{len(folds)}",
                f"{np.mean([v[0] for v in values]):.4f}",
                f"{fold_means[combo][worst][0]:.4f} ({worst})",
                _nanmean([v[1] for v in values], 4),
                _nanmean([v[2] for v in values], 3),
            ]
        )
    summary += [
        ["-", *_label(c), f"0/{len(folds)}", TBD, TBD, TBD, TBD]
        for c in combos
        if c not in fold_means
    ]
    lines += table(
        [
            "rank",
            "backbone",
            "mode",
            "aug",
            "folds",
            "mean held-out macro-F1",
            "lowest fold",
            "mean NWRD recall",
            "mean confidently wrong",
        ],
        summary,
    )
    pooled = {k[1:]: v for k, v in grouped.items() if k[0] == "pooled"}
    if pooled:
        lines += ["", "## Pooled split (development only)", ""]
        lines += table(
            ["backbone", "mode", "aug", "seeds", "test macro-F1", "NWRD recall", "ECE"],
            [
                [
                    *_label(c),
                    f"{len(s)}/{n_seeds}",
                    _cell(s, "heldout_macro_f1"),
                    _cell(s, "nwrd_recall_yellow_rust"),
                    _cell(s, "heldout_ece"),
                ]
                for c, s in sorted(pooled.items())
            ],
        )
    return lines


def write_results(cfg, doc: Path = DOC) -> Path:
    dvc = dvc_hashes(cfg.data.splits_csv)
    grouped = latest_by_seed(load_runs(cfg, dvc["dvc.splits_md5"]))
    folds = available_folds(cfg.data.splits_csv)
    lines = render(cfg, grouped, folds, fold_classes(cfg.data.splits_csv), dvc)
    text = doc.read_text(encoding="utf-8") if doc.exists() else f"{INTRO}{START}\n{END}\n"
    doc.write_text(replace_section(text, lines), encoding="utf-8")
    return doc


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/vision/wheat_v2.yaml")
    parser.add_argument("--doc", type=Path, default=DOC)
    args = parser.parse_args()
    print(write_results(load_config(args.config), args.doc))


if __name__ == "__main__":
    main()
