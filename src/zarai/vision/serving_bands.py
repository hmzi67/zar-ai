"""How the served model's confidence bands split the pooled test split and NWRD, and how accurate
each band is. Uses the logits the run logged at evaluation and its val-fitted temperature, so it
needs no GPU. Writes experiments/serving_bands.md.
"""

import argparse
import json
from pathlib import Path

import numpy as np

from zarai.vision.serving import BANDS, band_of

DOC = Path("experiments/serving_bands.md")
SPLITS = {
    "heldout": "Pooled test split (unseen images from the training sources)",
    "nwrd": "NWRD field tiles (never trained on; all yellow_rust)",
}


def band_table(probs: np.ndarray, labels: np.ndarray, bands) -> list[dict]:
    top = probs.max(axis=1)
    correct = probs.argmax(axis=1) == labels
    assigned = np.array([band_of(float(p), bands) for p in top])
    rows = []
    for band in BANDS:
        chosen = assigned == band
        rows.append(
            {
                "band": band,
                "n": int(chosen.sum()),
                "share": float(chosen.mean()),
                "accuracy": float(correct[chosen].mean()) if chosen.any() else None,
            }
        )
    return rows


def render(run_id: str, temperature: float, bands, results: dict) -> list[str]:
    from zarai.vision.results import table

    lines = [
        "# Confidence bands for the served model",
        "",
        f"Generated by `python -m zarai.vision.serving_bands` for run `{run_id}` "
        f"(configs/vision/serving.yaml), from the logits it logged at evaluation, with its "
        f"val-fitted temperature {temperature:.4f}. Bands on the top calibrated probability: "
        f"**confident** ≥ {bands['answer']:.2f} (answer), **likely** {bands['likely']:.2f}–"
        f"{bands['answer']:.2f} (answer as \"probably\" and ask a confirming question), **unsure** "
        f"< {bands['likely']:.2f} (ask for a clearer photo). Accuracy is of the top class.",
        "",
        "The plant filter runs before this and is not applied here (it turns away about 1% of "
        "wheat photos; experiments/plant_filter.md).",
        "",
    ]
    for split, title in SPLITS.items():
        rows = results[split]
        n = sum(r["n"] for r in rows)
        lines += [f"## {title}: {n} images", ""]
        lines += table(
            ["band", "images", "share", "accuracy"],
            [
                [
                    r["band"],
                    r["n"],
                    f"{r['share']:.1%}",
                    "-" if r["accuracy"] is None else f"{r['accuracy']:.3f}",
                ]
                for r in rows
            ],
        )
        answered = [r for r in rows if r["band"] != "unsure"]
        n_answered = sum(r["n"] for r in answered)
        if n_answered:
            acc = (
                sum(r["n"] * r["accuracy"] for r in answered if r["accuracy"] is not None)
                / n_answered
            )
            lines += [
                "",
                f"Answered (confident + likely): {n_answered / n:.1%} of images, accuracy {acc:.3f}.",
            ]
        lines.append("")
    return lines


def main(argv=None) -> None:
    import mlflow
    from omegaconf import OmegaConf

    from zarai.vision.calibrate import apply_temperature
    from zarai.vision.tracking import artifact_path, set_tracking_uri

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--serving-config", default="configs/vision/serving.yaml")
    parser.add_argument("--doc", type=Path, default=DOC)
    args = parser.parse_args(argv)
    cfg = OmegaConf.load(args.serving_config)
    set_tracking_uri(cfg.mlflow.tracking_uri)
    temperature = float(mlflow.get_run(cfg.run_id).data.metrics["temperature"])
    bands = {"answer": float(cfg.bands.answer), "likely": float(cfg.bands.likely)}
    results = {}
    for split in SPLITS:
        data = np.load(artifact_path(cfg.run_id, f"eval/{split}/{split}_logits.npz"))
        probs = apply_temperature(data["logits"], temperature)
        results[split] = band_table(probs, data["labels"], bands)
    args.doc.write_text(
        "\n".join(render(cfg.run_id, temperature, bands, results)), encoding="utf-8"
    )
    print(json.dumps(results, indent=1))
    print(args.doc)


if __name__ == "__main__":
    main()
