def render(cfg, results) -> list[str]:
    names = [v.name for v in cfg.variants]
    ks = [k for k in cfg.ks if k]
    checks = {name: verdicts(cfg, results.get(name, {})) for name in names}
    criteria = [c for c, _, _ in next(iter(checks.values()), [])]
    short = ["shortcut", "ablation", "Grad-CAM", "collateral", "transfer gain", "transfer healthy"]
    lines = [
        "## Summary",
        "",
        "Pass/fail per criterion, mean over 5 draws at k = 25 and 50. A variant needs at least 5 "
        "of 6 to be worth keeping.",
        "",
    ]
    lines += table(
        ["variant", *short[: len(criteria)], "passed"],
        [
            [
                f"`{name}`",
                *["pass" if ok else "fail" for _, _, ok in checks[name]],
                f"**{sum(bool(ok) for _, _, ok in checks[name])}/{len(checks[name])}**",
            ]
            for name in names
        ],
    )
    lines += ["", "Criteria (unchanged from the first controls run):", ""]
    lines += [f"{i}. {c}" for i, c in enumerate(criteria, 1)]
    lines += ["", "## Pooled test split recall per class after adaptation", ""]
    rows = []
    base = next(iter(results.values()), {}).get(("pooled", 0), [])
    rows.append(
        [
            "none (pooled model)",
            0,
            *[_cell([r.get(f"pooled_recall_{c}") for r in base]) for c in CLASSES],
            _cell([r.get("pooled_test_macro_f1") for r in base]),
        ]
    )
    for name in names:
        for k in ks:
            found = results.get(name, {}).get(("pooled", k), [])
            rows.append(
                [
                    f"`{name}`",
                    k,
                    *[_cell([r.get(f"pooled_recall_{c}") for r in found]) for c in CLASSES],
                    _cell([r.get("pooled_test_macro_f1") for r in found]),
                ]
            )
    lines += table(["variant", "k", *[f"`{c}`" for c in CLASSES], "macro-F1"], rows)
    columns = [
        ("NWRD recall", "pooled", "nwrd_test_recall"),
        ("rust inpainted", "pooled", "nwrd_ablated_recall"),
        ("empty leaf → yellow", "pooled", "empty_leaf_yellow"),
        ("CAM lift", "pooled", "cam_lift"),
        ("brown → yellow", "pooled", "pooled_as_yellow_brown_rust"),
        ("Ethiopia yellow recall", "transfer", "ethiopia_recall_yellow_rust"),
        ("Ethiopia healthy → disease", "transfer", "ethiopia_healthy_called_disease"),
    ]
    for name in names:
        lines += ["", f"## `{name}`", ""]
        lines += table(
            ["criterion", "observed", "result"],
            [[c, seen, "pass" if ok else "**fail**"] for c, seen, ok in checks[name]],
        )
        lines.append("")
        found = results.get(name, {})
        lines += table(
            ["k", *[c for c, _, _ in columns]],
            [
                [
                    k,
                    *[
                        _cell([r.get(key) for r in found.get((kind, k), [])])
                        for _, kind, key in columns
                    ],
                ]
                for k in cfg.ks
            ],
        )
    return lines


def write_report(cfg) -> Path:
    doc = Path(cfg.output.doc)
    text = doc.read_text(encoding="utf-8") if doc.exists() else f"{INTRO}{START}\n{END}\n"
    doc.write_text(replace_section(text, render(cfg, load_results(cfg))), encoding="utf-8")
    return doc


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/vision/wheat_v2_fewshot_rehearsal.yaml")
    parser.add_argument("--only", nargs="*", help="variant names to run")
    parser.add_argument("--report-only", action="store_true")
    args = parser.parse_args(argv)
    cfg = load_cfg(args.config)
    if not args.report_only:
        chosen = [v for v in cfg.variants if not args.only or v.name in args.only]
        run_controls(cfg, get_logger(__name__), [(v.name, make_hook(cfg, v)) for v in chosen])
    print(write_report(cfg))


if __name__ == "__main__":
    main()
