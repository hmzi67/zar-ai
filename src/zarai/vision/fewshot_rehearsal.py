# Adaptation


def set_trainable(model, trainable: str) -> None:
    for name, param in model.named_parameters():
        if trainable == "full":
            param.requires_grad = True
        elif trainable == "head_last2":
            last = {f"blocks.{i}." for i in (len(model.blocks) - 2, len(model.blocks) - 1)}
            param.requires_grad = name.startswith(("head.", "norm.", "fc_norm.", *last))
        elif trainable == "lora":
            param.requires_grad = "lora_" in name or name.startswith("head.")
        else:
            raise ValueError(f"unknown trainable setting {trainable!r}")


def add_lora(model, rank: int):
    from peft import LoraConfig, inject_adapter_in_model

    from zarai.vision.backbones import LORA_TARGETS

    config = LoraConfig(
        r=rank, lora_alpha=rank, lora_dropout=0.0, target_modules=LORA_TARGETS, bias="none"
    )
    return inject_adapter_in_model(config, model)


def optimiser_groups(model, run_cfg, lr: float, weight_decay: float, layer_decay: bool):
    """Layer-wise LR decay groups as in training (full ViT), keeping only trainable tensors."""
    from zarai.vision import backbones

    tuned = copy.deepcopy(run_cfg)
    tuned.train.lr, tuned.train.weight_decay = lr, weight_decay
    tuned.model.mode = "full" if layer_decay else "lora"
    groups = []
    for group in backbones.param_groups(model, tuned):
        params = [p for p in group["params"] if p.requires_grad]
        if params:
            groups.append({**group, "params": params})
    return groups


def train_balanced(cfg, env, model, groups, param_groups, seed: int, l2sp_alpha: float = 0.0):
    """cfg.rehearsal.steps steps; each batch has per_class images of every class."""
    import torch
    from torch.utils.data import DataLoader

    from zarai.vision.transforms import build_train_transforms

    r, run_cfg, classes = cfg.rehearsal, env["run_cfg"], env["classes"]
    transform = build_train_transforms(
        env["few"].adapt.aug,
        run_cfg.data.image_size,
        env["mean"],
        env["std"],
        run_cfg.train.augment,
    )
    items, ranges = [], []
    for label, sources in groups.items():
        ranges.append((len(items), len(sources)))
        items += [(s, classes.index(label)) for s in sources]
    rng = np.random.default_rng(seed)
    order = [
        int(start + i)
        for _ in range(r.steps)
        for start, n in ranges
        for i in rng.integers(0, n, r.per_class)
    ]
    loader = DataLoader(
        ItemsDataset(items, transform),
        batch_size=r.per_class * len(ranges),
        sampler=order,
        num_workers=env["few"].adapt.num_workers,
        pin_memory=True,
    )
    anchor = {}
    if l2sp_alpha:
        anchor = {
            n: p.detach().clone()
            for n, p in model.named_parameters()
            if p.requires_grad and not n.startswith("head.")
        }
    optimizer = torch.optim.AdamW(param_groups)
    criterion = torch.nn.CrossEntropyLoss(label_smoothing=r.label_smoothing)
    model.train()
    torch.manual_seed(seed)
    device = env["device"]
    for images, targets in loader:
        with torch.autocast(device_type=device, dtype=torch.bfloat16):
            loss = criterion(model(images.to(device)), targets.to(device))
        if anchor:
            params = dict(model.named_parameters())
            drift = sum(((params[n].float() - w0.float()) ** 2).sum() for n, w0 in anchor.items())
            loss = loss + l2sp_alpha / 2 * drift
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()
    model.eval()


def make_hook(cfg, variant):
    """hook(model, env, kind, k, index, drawn) -> adapted model, for run_controls."""

    def hook(model, env, kind, k, index, drawn):
        r = cfg.rehearsal
        groups = class_groups(cfg, env, k, index, drawn, bool(variant.get("lesion_crop")))
        trainable = variant.trainable
        if trainable == "lora":
            model = add_lora(copy.deepcopy(model), int(variant.lora_rank))
        set_trainable(model, trainable)
        alpha = float(variant.get("l2sp_alpha", 0.0))
        param_groups = optimiser_groups(
            model,
            env["run_cfg"],
            lr=r.lr.lora if trainable == "lora" else r.lr.full,
            weight_decay=0.0 if alpha else r.weight_decay,
            layer_decay=trainable != "lora",
        )
        train_balanced(
            cfg, env, model, groups, param_groups, seed=1000 * k + index, l2sp_alpha=alpha
        )
        return model

    return hook


