"""Rehearsal few-shot adaptation to NWRD, judged by the controls in zarai.vision.fewshot_controls.

Every batch mixes the k NWRD yellow_rust tiles with brown_rust, black_rust, septoria and healthy
images from the train split, so the model has to keep the classes apart while it adapts. Variants
limit how far the weights can move (head + last 2 blocks, LoRA rank 8, L2-SP toward the pooled
weights) or crop the NWRD tiles to the lesion. The controls, their data and the criteria are
those of configs/vision/wheat_v2_fewshot_controls.yaml, unchanged.
"""

import argparse
import copy
import io
from functools import cache
from pathlib import Path

import numpy as np

from zarai.common.logging import get_logger
from zarai.vision.fewshot_controls import (
    _cell,
    _jpeg,
    load_results,
    raw_paths,
    run_controls,
    tile_offsets,
    verdicts,
)
from zarai.vision.fewshot_nwrd import HEALTHY, YELLOW, nwrd_image_id
from zarai.vision.results import END, START, replace_section, table

REHEARSED = ("brown_rust", "black_rust", "septoria")  # healthy comes with the yellow_rust draw
CLASSES = ("black_rust", "brown_rust", "healthy", "septoria", "yellow_rust")
INTRO = """# wheat_v2 few-shot NWRD adaptation with rehearsal: controls per variant

The plain few-shot adaptation failed 5 of the 6 controls
(experiments/wheat_v2_fewshot_controls.md): it learned "NWRD field, or anything rust-coloured,
is yellow_rust". This is the last attempt. Every batch rehearses the other classes, with four
variants that limit drift or focus on the lesion, judged by the same controls and criteria.
Generated by `python -m zarai.vision.fewshot_rehearsal` from the MLflow experiment
`wheat_v2_fewshot_rehearsal` (configs/vision/wheat_v2_fewshot_rehearsal.yaml). Don't edit between
the markers.

"""


def load_cfg(path: str):
    """The rehearsal config on top of the controls config it names."""
    from omegaconf import OmegaConf

    own = OmegaConf.load(path)
    base = OmegaConf.load(own.controls_config)
    return OmegaConf.merge(base, own)


# ---------------------------------------------------------------------------------------------
# Training data


@cache
def lesion_crop(original_path: str, tile_size: int, pad_share: float, min_pad: int, min_side: int):
    """JPEG of a square around the largest rust region of an NWRD tile, padded for context. The
    crop can reach past the tile into the rest of the photo."""
    import cv2
    from PIL import Image

    row = {"original_path": original_path}
    image_path, mask_path = raw_paths(nwrd_image_id(row))
    left, top = tile_offsets(row)
    with Image.open(mask_path) as m:
        mask = np.asarray(m.convert("L")) > 0
    tile = mask[top : top + tile_size, left : left + tile_size].astype(np.uint8)
    count, _, stats, _ = cv2.connectedComponentsWithStats(tile, connectivity=8)
    if count < 2:
        raise ValueError(f"{original_path}: no rust in the mask")
    largest = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
    x, y, w, h = (int(v) for v in stats[largest, :4])
    side = max(max(w, h) + 2 * max(min_pad, round(pad_share * max(w, h))), min_side)
    with Image.open(image_path) as source:
        image = source.convert("RGB")  # not EXIF-rotated, like the masks
    side = min(side, *image.size)
    cx, cy = left + x + w / 2, top + y + h / 2
    x0 = int(min(max(cx - side / 2, 0), image.size[0] - side))
    y0 = int(min(max(cy - side / 2, 0), image.size[1] - side))
    return _jpeg(image.crop((x0, y0, x0 + side, y0 + side)))


def class_groups(cfg, env, k: int, index: int, drawn, lesion: bool) -> dict[str, list]:
    """{class: [path or JPEG bytes]}: the drawn yellow_rust and healthy, and k of each other class
    from this model's train split. Seeded by (k, index), so every variant gets the same images."""
    rows, column = env["rows"], env["train_column"]
    rng = np.random.default_rng([k, index, 17])
    groups = {
        YELLOW: [r["original_path"] for r in drawn if r["label"] == YELLOW],
        HEALTHY: [r["path"] for r in drawn if r["label"] == HEALTHY],
    }
    if lesion:
        lc = cfg.rehearsal.lesion
        size = cfg.controls.empty_tiles.tile_size
        groups[YELLOW] = [
            lesion_crop(p, size, lc.pad_share, lc.min_pad, lc.min_side) for p in groups[YELLOW]
        ]
    else:
        groups[YELLOW] = [r["path"] for r in drawn if r["label"] == YELLOW]
    for label in REHEARSED:
        pool = [r for r in rows if r["label"] == label and r[column] == "train"]
        if len(pool) < k:
            raise ValueError(f"{label}: only {len(pool)} train images for k = {k}")
        groups[label] = [pool[i]["path"] for i in sorted(rng.choice(len(pool), k, replace=False))]
    return groups


class ItemsDataset:
    """(image, class index) for items that are a path or JPEG bytes."""

    def __init__(self, items, transform):
        self.items, self.transform = items, transform

    def __len__(self):
        return len(self.items)

    def __getitem__(self, index):
        from PIL import Image

        source, label = self.items[index]
        handle = io.BytesIO(source) if isinstance(source, bytes) else source
        with Image.open(handle) as image:
            return self.transform(image.convert("RGB")), label


