"""Build the generated part of experiments/wheat_v2_analysis.md: where each class comes from, and
how per-class recall on a held-out source depends on it.

Counts come from data/splits/wheat_v2.csv. Recall and confusions come from the finished, non-dry
LOSO runs in MLflow on the current dataset version (latest run per seed), and are only ever
logged numbers. The interpretation below the markers is written by hand.
"""

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

from zarai.common.config import load_config
from zarai.common.io import read_csv
from zarai.vision.data_v2 import available_folds
from zarai.vision.eval_external import _mean_sd
from zarai.vision.results import END, START, TBD, replace_section, table
from zarai.vision.results_v2 import load_runs
from zarai.vision.tracking import dvc_hashes

DOC = Path("experiments/wheat_v2_analysis.md")
INTRO = """# wheat_v2 analysis: class-source confounding

Where each class's images come from, and what that does to per-class recall on a source the model
never saw. The tables are generated by `python -m zarai.vision.analysis_v2` from
`data/splits/wheat_v2.csv` and the MLflow experiment `wheat_v2`. Don't edit between the markers.

"""


def source_class_counts(rows, sources, classes) -> dict[tuple[str, str], int]:
    return Counter((r["source"], r["label"]) for r in rows if r["source"] in sources)


def class_sources(counts, sources, classes, exclude=()) -> dict[str, list[tuple[str, int]]]:
    """{class: [(source, images)] largest first}, over sources not in exclude."""
    found = {}
    for c in classes:
        found[c] = sorted(
            ((s, counts[s, c]) for s in sources if s not in exclude and counts[s, c]),
            key=lambda item: -item[1],
        )
    return found


def fold_training(rows, fold: str, classes) -> dict[str, Counter]:
    """{class: Counter(source -> train images)} for one LOSO fold."""
    column = f"split_loso_{fold}"
    found = {c: Counter() for c in classes}
    for r in rows:
        if r[column] == "train":
            found[r["label"]][r["source"]] += 1
    return found


def grouped_runs(cfg):
    """{(fold, backbone, mode, aug): {seed: run}} for LOSO runs, latest run per seed."""
    splits_md5 = dvc_hashes(cfg.data.splits_csv)["dvc.splits_md5"]
    grouped = defaultdict(dict)
    for run in load_runs(cfg, splits_md5):
        t = run.data.tags
        if t.get("protocol") != "loso" or t.get("background", "none") != "none":
            continue
        grouped[t["fold"], t["backbone"], t["mode"], t["aug"]][t["seed"]] = run
    return grouped


def confusion_shares(runs, classes) -> dict[str, Counter]:
    """{true class: Counter(predicted class -> share)} summed over runs' held-out confusions."""
    import mlflow

    total = np.zeros((len(classes), len(classes)))
    for run in runs:
        path = mlflow.artifacts.download_artifacts(
            run_id=run.info.run_id, artifact_path="eval/heldout/heldout_confusion.json"
        )
        entry = json.loads(Path(path).read_text(encoding="utf-8"))
        if entry["classes"] != classes:
            raise ValueError(f"{run.info.run_id}: unexpected class order {entry['classes']}")
        total += np.array(entry["matrix"])
    shares = {}
    for i, c in enumerate(classes):
        if total[i].sum():
            shares[c] = Counter(
                {classes[j]: total[i, j] / total[i].sum() for j in range(len(classes))}
            )
    return shares


def render(cfg, rows, grouped, confusions) -> list[str]:
    classes = list(cfg.data.classes)
    test_only = set(cfg.data.test_only_sources)
    sources = sorted({r["source"] for r in rows}, key=lambda s: (s in test_only, s))
    folds = available_folds(cfg.data.splits_csv)
    counts = source_class_counts(rows, sources, classes)
    by_class = class_sources(counts, sources, classes, exclude=test_only)
    combos = sorted({key[1:] for key in grouped})
    lines = [
        f"Dataset: splits `{dvc_hashes(cfg.data.splits_csv)['dvc.splits_md5']}`. "
        f"{len(combos)} configurations, {sum(len(s) for s in grouped.values())} LOSO runs.",
        "",
        "## 1. Images per source and class",
        "",
        "All images in wheat_v2 (any split). NWRD is test-only, so it isn't counted as a training "
        "source in the last three columns.",
        "",
    ]
    lines += table(
        [
            "class",
            *sources,
            "training sources",
            "largest training source",
            "share of class",
        ],
        [
            [
                f"`{c}`",
                *[counts[s, c] for s in sources],
                len(by_class[c]),
                by_class[c][0][0] if by_class[c] else "-",
                (
                    f"{by_class[c][0][1] / sum(n for _, n in by_class[c]):.1%}"
                    if by_class[c]
                    else "-"
                ),
            ]
            for c in classes
        ],
    )
    few = [c for c in classes if len(by_class[c]) <= 2]
    lines += [
        "",
        "Classes from only one or two training sources: "
        + (
            ", ".join(f"`{c}` (" + ", ".join(f"{s} {n}" for s, n in by_class[c]) + ")" for c in few)
            or "none"
        )
        + ".",
        "",
        "## 2. What each fold trains each class on",
        "",
        "Training images per class in each LOSO fold, by source. A class whose only source is held "
        "out has to be learned from whatever remains.",
        "",
    ]
    train = {fold: fold_training(rows, fold, classes) for fold in folds}
    lines += table(
        ["held out", *[f"`{c}`" for c in classes]],
        [
            [
                fold,
                *[
                    (
                        " + ".join(f"{s} {n}" for s, n in train[fold][c].most_common())
                        if train[fold][c]
                        else "**0**"
                    )
                    for c in classes
                ],
            ]
            for fold in folds
        ],
    )
    present = {
        fold: [c for c in classes if any(r["source"] == fold and r["label"] == c for r in rows)]
        for fold in folds
    }

    def recall_values(fold, combo, c):
        return [
            run.data.metrics.get(f"heldout_recall_{c}")
            for run in grouped.get((fold, *combo), {}).values()
        ]

    lines += [
        "",
        "## 3. Per-class recall by held-out source",
        "",
        "Each cell is the mean, over the configurations that ran, of each configuration's mean "
        "recall across seeds, with the lowest and highest configuration in brackets. Train images "
        "and sources are that class's training data in the fold.",
        "",
    ]
    summary = []
    for fold in folds:
        for c in present[fold]:
            means = [
                np.mean(v)
                for combo in combos
                if (v := recall_values(fold, combo, c)) and None not in v
            ]
            summary.append(
                [
                    fold,
                    f"`{c}`",
                    sum(train[fold][c].values()),
                    len(train[fold][c]),
                    (f"{np.mean(means):.3f} [{min(means):.3f}-{max(means):.3f}]" if means else TBD),
                ]
            )
    lines += table(
        ["held out", "class", "train images", "train sources", "recall (mean [min-max])"], summary
    )
    lines += ["", "### By configuration", "", "Mean ± SD over seeds.", ""]
    for fold in folds:
        lines += [f"**Held out: {fold}**", ""]
        lines += table(
            ["backbone", "mode", "aug", *[f"`{c}`" for c in present[fold]]],
            [
                [
                    *combo,
                    *[_mean_sd(recall_values(fold, combo, c), 3) or TBD for c in present[fold]],
                ]
                for combo in combos
            ],
        )
        lines.append("")
    lines += [
        "## 4. What held-out images are predicted as",
        "",
        "Share of each held-out class's images predicted as each class, summed over every LOSO run "
        "of every configuration (all seeds).",
        "",
    ]
    rows_out = []
    for fold in folds:
        for c in present[fold]:
            shares = confusions.get(fold, {}).get(c)
            rows_out.append(
                [
                    fold,
                    f"`{c}`",
                    *([f"{shares[p]:.3f}" for p in classes] if shares else [TBD] * len(classes)),
                ]
            )
    lines += table(["held out", "true class", *[f"→ `{p}`" for p in classes]], rows_out)
    return lines


def write_analysis(cfg, doc: Path = DOC) -> Path:
    rows = read_csv(cfg.data.splits_csv)
    grouped = grouped_runs(cfg)
    folds = available_folds(cfg.data.splits_csv)
    confusions = {
        fold: confusion_shares(
            [run for key, seeds in grouped.items() if key[0] == fold for run in seeds.values()],
            list(cfg.data.classes),
        )
        for fold in folds
    }
    lines = render(cfg, rows, grouped, confusions)
    text = doc.read_text(encoding="utf-8") if doc.exists() else f"{INTRO}{START}\n{END}\n"
    doc.write_text(replace_section(text, lines), encoding="utf-8")
    return doc


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/vision/wheat_v2.yaml")
    parser.add_argument("--doc", type=Path, default=DOC)
    args = parser.parse_args()
    print(write_analysis(load_config(args.config), args.doc))


if __name__ == "__main__":
    main()
