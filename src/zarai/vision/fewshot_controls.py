"""Controls for the few-shot NWRD adaptation: did the model learn stripe rust, or the NWRD field?

Each adaptation repeats one from zarai.vision.fewshot_nwrd (same NWRD split, draws and budget) and
is scored on five controls (configs/vision/wheat_v2_fewshot_controls.yaml):
1. shortcut: NWRD test-image tiles with an empty rust mask, mostly leaf, not touching marked rust;
2. lesion ablation: the NWRD test rust tiles with the marked rust inpainted;
3. Grad-CAM for yellow_rust against the rust mask;
4. collateral: per-class recall on the pooled test split;
5. transfer: the same adaptation applied to the LOSO model that never saw Ethiopia, scored on
   Ethiopian stripe rust.
It also scores each adaptation on the NWRD adapt split, which is what picks the model to keep.
Every adaptation is one MLflow run; the report is built from MLflow.
"""

