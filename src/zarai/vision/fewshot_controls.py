def _jpeg(image, quality: int = 92) -> bytes:
    """Encode like the wheat_v2 export, so control tiles match the training images."""
    buffer = io.BytesIO()
    image.save(buffer, "JPEG", quality=quality)
    return buffer.getvalue()


def raw_paths(image_id: str) -> tuple[Path, Path]:
    """The NWRD image and rust mask for an image id, from train/ or test/."""
    for part in ("train", "test"):
        masks = NWRD_ROOT / part / "masks" / f"{image_id}.png"
        if masks.exists():
            images = list((NWRD_ROOT / part / "images").glob(f"{image_id}.*"))
            if len(images) != 1:
                raise FileNotFoundError(f"NWRD image {image_id}: found {images}")
            return images[0], masks
    raise FileNotFoundError(f"no NWRD mask for image {image_id}")


def tile_offsets(row: dict) -> tuple[int, int]:
    left, top = Path(row["original_path"]).stem.rsplit("_", 2)[1:]
    return int(left), int(top)


def empty_leaf_tiles(image_ids, tile_size: int, min_leaf_share: float) -> list[bytes]:
    """Tiles with no marked rust, mostly leaf, whose 8 neighbours have no marked rust either."""
    from PIL import Image

    from zarai.data.leaf_mask import leaf_mask
    from zarai.vision.eval_external import tile_boxes

    found = []
    for image_id in sorted(image_ids):
        image_path, mask_path = raw_paths(image_id)
        with Image.open(mask_path) as m:
            mask = np.asarray(m.convert("L")) > 0
        with Image.open(image_path) as source:
            image = source.convert("RGB")  # not EXIF-rotated, like the training tiles
        boxes = tile_boxes(mask.shape[1], mask.shape[0], tile_size)
        rust = {(b[0], b[1]) for b in boxes if mask[b[1] : b[3], b[0] : b[2]].any()}
        for left, top, right, bottom in boxes:
            near = any(
                (left + dx * tile_size, top + dy * tile_size) in rust
                for dx in (-1, 0, 1)
                for dy in (-1, 0, 1)
            )
            if near:
                continue
            tile = image.crop((left, top, right, bottom))
            leaf, fell_back = leaf_mask(np.asarray(tile))
            if not fell_back and leaf.mean() >= min_leaf_share:
                found.append(_jpeg(tile))
    return found


def rust_tiles(rows, tile_size: int, dilate_px: int, inpaint_radius: int):
    """For NWRD rust tile rows: (intact JPEGs, rust-inpainted JPEGs, rust masks at tile size)."""
    import cv2
    from PIL import Image

    intact, ablated, masks = [], [], []
    by_image = defaultdict(list)
    for row in rows:
        by_image[nwrd_image_id(row)].append(row)
    kernel = np.ones((dilate_px, dilate_px), np.uint8)
    for image_id, tiles in sorted(by_image.items()):
        image_path, mask_path = raw_paths(image_id)
        with Image.open(mask_path) as m:
            mask = np.asarray(m.convert("L")) > 0
        with Image.open(image_path) as source:
            image = np.asarray(source.convert("RGB"))
        for row in tiles:
            left, top = tile_offsets(row)
            tile = image[top : top + tile_size, left : left + tile_size]
            tile_mask = mask[top : top + tile_size, left : left + tile_size]
            grown = cv2.dilate(tile_mask.astype(np.uint8), kernel)
            filled = cv2.inpaint(tile, grown, inpaint_radius, cv2.INPAINT_TELEA)
            intact.append(_jpeg(Image.fromarray(tile)))
            ablated.append(_jpeg(Image.fromarray(filled)))
            masks.append(tile_mask)
    return intact, ablated, masks


class BytesDataset:
    def __init__(self, images: list[bytes], label: int, transform):
        self.images, self.label, self.transform = images, label, transform

    def __len__(self):
        return len(self.images)

    def __getitem__(self, index):
        from PIL import Image

        with Image.open(io.BytesIO(self.images[index])) as image:
            return self.transform(image.convert("RGB")), self.label


def mask_in_model_space(mask: np.ndarray, eval_resize: int, image_size: int) -> np.ndarray:
    """Apply the eval transform's geometry (resize short side, centre crop) to a mask."""
    from PIL import Image

    height, width = mask.shape
    scale = eval_resize / min(height, width)
    size = (round(width * scale), round(height * scale))
    resized = np.asarray(Image.fromarray(mask.astype(np.uint8) * 255).resize(size, 0)) > 127
    top = (resized.shape[0] - image_size) // 2
    left = (resized.shape[1] - image_size) // 2
    return resized[top : top + image_size, left : left + image_size]


