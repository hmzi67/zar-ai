def best_loso_run(training_cfg, fold: str, backbone: str, mode: str, aug: str):
    from zarai.vision.results_v2 import load_runs

    splits_md5 = dvc_hashes(training_cfg.data.splits_csv)["dvc.splits_md5"]
    runs = [
        r
        for r in load_runs(training_cfg, splits_md5)
        if r.data.tags.get("protocol") == "loso"
        and r.data.tags.get("fold") == fold
        and (r.data.tags["backbone"], r.data.tags["mode"], r.data.tags["aug"])
        == (backbone, mode, aug)
        and r.data.tags.get("background", "none") == "none"
    ]
    if not runs:
        raise ValueError(f"no LOSO {fold} run of {backbone}/{mode}/{aug}")
    return max(runs, key=lambda r: r.data.metrics["best_val_macro_f1"])


def run_controls(cfg, log) -> None:
    import mlflow
    import torch
    from omegaconf import OmegaConf
    from torch.utils.data import DataLoader

    from zarai.common.config import load_config
    from zarai.vision import backbones
    from zarai.vision.transforms import build_transforms

    few = load_config(cfg.fewshot_config)
    training_cfg = load_config(few.training_config)
    rows = read_csv(training_cfg.data.splits_csv)
    sets = adaptation_sets(training_cfg.data.splits_csv, few.nwrd)
    nwrd = [r for r in rows if r["source"] == "nwrd"]
    side = split_nwrd_images(nwrd, few.nwrd.adapt_share, few.nwrd.split_seed)
    test_images = {i for i, s in side.items() if s == "test"}
    c = cfg.controls
    log.info("building control tiles")
    intact, ablated, masks = rust_tiles(
        sets["test_yellow"],
        c.empty_tiles.tile_size,
        c.ablation.dilate_px,
        c.ablation.inpaint_radius,
    )
    empty = empty_leaf_tiles(test_images, c.empty_tiles.tile_size, c.empty_tiles.min_leaf_share)
    log.info("NWRD test: %d rust tiles, %d empty leaf tiles", len(intact), len(empty))
    val_healthy = [r for r in rows if r["label"] == HEALTHY and r["split_pooled"] == "val"]
    pooled_test = [r for r in rows if r["split_pooled"] == "test"]
    fold_col = f"split_loso_{cfg.controls.transfer_fold}"
    ethiopia = [r for r in rows if r["source"] == cfg.controls.transfer_fold]
    fold_healthy = [r for r in rows if r["label"] == HEALTHY and r[fold_col] == "train"]

    splits_md5 = dvc_hashes(training_cfg.data.splits_csv)["dvc.splits_md5"]
    set_tracking_uri(cfg.mlflow.tracking_uri)
    mlflow.set_experiment(cfg.mlflow.experiment)
    device = "cuda"
    m = cfg.model
    sources = {
        "pooled": best_pooled_run(training_cfg, m.backbone, m.mode, m.aug),
        "transfer": best_loso_run(
            training_cfg, cfg.controls.transfer_fold, m.backbone, m.mode, m.aug
        ),
    }
    best = None
    for kind, source in sources.items():
        model, checkpoint, run_cfg = load_run_model(source.info.run_id, device)
        classes, mean, std = checkpoint["classes"], checkpoint["mean"], checkpoint["std"]
        yellow = classes.index(YELLOW)
        base_state = backbones.checkpoint_state(model, run_cfg.model.mode)
        transform = build_transforms(
            run_cfg.data.image_size,
            train=False,
            mean=mean,
            std=std,
            eval_resize=run_cfg.data.eval_resize,
        )
        model_masks = [
            mask_in_model_space(mk, run_cfg.data.eval_resize, run_cfg.data.image_size)
            for mk in masks
        ]

        def loader(dataset, batch=few.adapt.eval_batch_size):
            return DataLoader(dataset, batch_size=batch, num_workers=few.adapt.num_workers)

        loaders = {"nwrd_rust": loader(BytesDataset(intact, yellow, transform), 32)}
        if kind == "pooled":
            loaders |= {
                "nwrd_ablated": loader(BytesDataset(ablated, yellow, transform)),
                "nwrd_empty": loader(BytesDataset(empty, yellow, transform)),
                "val_healthy": loader(RowsDataset(val_healthy, classes, transform)),
                "pooled_test": loader(RowsDataset(pooled_test, classes, transform)),
            }
        else:
            loaders["ethiopia"] = loader(RowsDataset(ethiopia, classes, transform))
            run_sets = {**sets, "adapt_healthy": fold_healthy}
        log.info("%s: run %s (seed %s)", kind, source.info.run_id, source.data.tags["seed"])
        for k in cfg.ks:
            for index in range(cfg.draws if k else 1):
                backbones.load_state(model, base_state, run_cfg.model.mode)
                drawn = []
                if k:
                    drawn = draw(sets if kind == "pooled" else run_sets, k, index)
                    adapt(
                        model,
                        few,
                        run_cfg,
                        drawn,
                        classes,
                        mean,
                        std,
                        device,
                        seed=1000 * k + index,
                    )
                if kind == "pooled":
                    used = {r["path"] for r in drawn}
                    rest = [r for r in sets["adapt_yellow"] if r["path"] not in used]
                    loaders["adapt_rest"] = loader(RowsDataset(rest, classes, transform))
                    metrics = score_pooled(model, loaders, model_masks, classes, device)
                else:
                    metrics = score_transfer(model, loaders, classes, device)
                with mlflow.start_run(run_name=f"{kind}_k{k}_d{index}"):
                    mlflow.set_tags(
                        {
                            "kind": kind,
                            "model": f"{m.backbone}/{m.mode}/{m.aug}",
                            "k": str(k),
                            "draw": str(index),
                            "source_run_id": source.info.run_id,
                            "source_seed": source.data.tags["seed"],
                        }
                    )
                    mlflow.log_params(
                        {
                            "dvc.splits_md5": splits_md5,
                            **{
                                f"controls.{key}": str(v)
                                for key, v in OmegaConf.to_container(c).items()
                            },
                        }
                    )
                    mlflow.log_metrics(metrics)
                    run_id = mlflow.active_run().info.run_id
                log.info(
                    "%s k=%d draw %d: %s",
                    kind,
                    k,
                    index,
                    {a: round(b, 3) for a, b in metrics.items()},
                )
                if kind == "pooled" and k in cfg.select.ks:
                    if best is None or metrics["select_score"] > best["select_score"]:
                        best = {
                            "select_score": metrics["select_score"],
                            "k": k,
                            "draw": index,
                            "control_run_id": run_id,
                            "source_run_id": source.info.run_id,
                            "state_dict": {
                                n: t.detach().cpu().clone() for n, t in model.state_dict().items()
                            },
                            "checkpoint": checkpoint,
                        }
        del model
        torch.cuda.empty_cache()
    out = Path(cfg.output.best_checkpoint)
    out.parent.mkdir(parents=True, exist_ok=True)
    saved = {
        **{key: v for key, v in best["checkpoint"].items() if key != "state_dict"},
        "state_dict": best["state_dict"],
        "trainable_only": False,
        "adapted": {
            key: best[key]
            for key in ("k", "draw", "select_score", "control_run_id", "source_run_id")
        },
    }
    torch.save(saved, out)
    log.info("best adapted model by adapt-split score: %s -> %s", saved["adapted"], out)


