def load_results(cfg) -> dict[tuple[str, int], list[dict]]:
    """{(kind, k): [metrics per draw]}, latest run per draw."""
    import mlflow

    set_tracking_uri(cfg.mlflow.tracking_uri)
    found: dict[tuple[str, int], dict[int, dict]] = defaultdict(dict)
    if mlflow.get_experiment_by_name(cfg.mlflow.experiment) is None:
        return {}
    runs = mlflow.search_runs(
        experiment_names=[cfg.mlflow.experiment],
        filter_string="attributes.status = 'FINISHED'",
        order_by=["attributes.start_time ASC"],
        output_format="list",
    )
    for run in runs:
        t = run.data.tags
        found[t["kind"], int(t["k"])][int(t["draw"])] = run.data.metrics
    return {key: list(draws.values()) for key, draws in found.items()}


def _mean(values) -> float | None:
    values = [v for v in values if v is not None]
    return float(np.mean(values)) if values else None


def _cell(values, digits=3) -> str:
    values = [v for v in values if v is not None]
    if not values:
        return TBD
    if len(values) == 1:
        return f"{values[0]:.{digits}f}"
    return f"{np.mean(values):.{digits}f} ± {np.std(values, ddof=1):.{digits}f}"


def verdicts(cfg, results) -> list[tuple[str, str, bool | None]]:
    """[(criterion, observed, passed)] on the mean over draws at the candidate ks."""
    crit, ks = cfg.criteria, list(cfg.select.ks)

    def pooled(metric):
        return _mean([r.get(metric) for k in ks for r in results.get(("pooled", k), [])])

    def base(kind, metric):
        return _mean([r.get(metric) for r in results.get((kind, 0), [])])

    def transfer(metric):
        return _mean([r.get(metric) for k in ks for r in results.get(("transfer", k), [])])

    out = []
    recall, empty, ablated = (
        pooled("nwrd_test_recall"),
        pooled("empty_leaf_yellow"),
        pooled("nwrd_ablated_recall"),
    )
    if None not in (recall, empty):
        out.append(
            (
                "Shortcut: empty leaf tiles called yellow_rust ≤ "
                f"{crit.shortcut_max_ratio} × NWRD recall",
                f"{empty:.3f} vs {recall:.3f} (ratio {empty / recall:.2f})",
                empty <= crit.shortcut_max_ratio * recall,
            )
        )
    if None not in (recall, ablated):
        out.append(
            (
                f"Ablation: recall with rust inpainted ≤ {crit.ablation_max_ratio} × intact recall",
                f"{ablated:.3f} vs {recall:.3f} (ratio {ablated / recall:.2f})",
                ablated <= crit.ablation_max_ratio * recall,
            )
        )
    lift = pooled("cam_lift")
    if lift is not None:
        out.append(
            (
                f"Grad-CAM: mass in rust / rust area ≥ {crit.cam_min_lift}",
                f"{lift:.2f} (before adaptation {base('pooled', 'cam_lift'):.2f})",
                lift >= crit.cam_min_lift,
            )
        )
    classes = [c for c in ("black_rust", "brown_rust", "healthy", "septoria", "yellow_rust")]
    drops = {
        c: base("pooled", f"pooled_recall_{c}") - pooled(f"pooled_recall_{c}")
        for c in classes
        if pooled(f"pooled_recall_{c}") is not None
        and base("pooled", f"pooled_recall_{c}") is not None
    }
    if drops:
        worst = max(drops, key=drops.get)
        out.append(
            (
                f"Collateral: no pooled-test class recall falls > {crit.collateral_max_drop}",
                f"largest drop {drops[worst]:+.3f} ({worst})",
                drops[worst] <= crit.collateral_max_drop,
            )
        )
    gain_after, gain_before = transfer("ethiopia_recall_yellow_rust"), base(
        "transfer", "ethiopia_recall_yellow_rust"
    )
    if None not in (gain_after, gain_before):
        out.append(
            (
                f"Transfer: Ethiopian yellow_rust recall rises ≥ {crit.transfer_min_gain}",
                f"{gain_before:.3f} → {gain_after:.3f}",
                gain_after - gain_before >= crit.transfer_min_gain,
            )
        )
    h_after, h_before = transfer("ethiopia_healthy_called_disease"), base(
        "transfer", "ethiopia_healthy_called_disease"
    )
    if None not in (h_after, h_before):
        out.append(
            (
                f"Transfer: Ethiopian healthy called a disease rises ≤ {crit.transfer_max_healthy_rise}",
                f"{h_before:.3f} → {h_after:.3f}",
                h_after - h_before <= crit.transfer_max_healthy_rise,
            )
        )
    return out


def render(cfg, results) -> list[str]:
    ks = list(cfg.ks)
    lines = ["## Verdict", "", f"Mean over draws at k = {', '.join(map(str, cfg.select.ks))}.", ""]
    checks = verdicts(cfg, results)
    lines += table(
        ["criterion", "observed", "result"],
        [[name, seen, "pass" if ok else "**fail**"] for name, seen, ok in checks],
    )
    lines += ["", "## NWRD controls (pooled model)", ""]
    pooled_cols = [
        ("NWRD rust recall", "nwrd_test_recall"),
        ("rust inpainted", "nwrd_ablated_recall"),
        ("empty leaf → yellow", "empty_leaf_yellow"),
        ("empty leaf → healthy", "empty_leaf_healthy"),
        ("CAM mass in rust", "cam_mass_in_rust"),
        ("rust area", "cam_rust_area"),
        ("CAM lift", "cam_lift"),
        ("CAM peak on rust", "cam_peak_on_rust"),
    ]
    lines += table(
        ["k", "draws", *[n for n, _ in pooled_cols]],
        [
            [
                k,
                len(results.get(("pooled", k), [])),
                *[
                    _cell([r.get(key) for r in results.get(("pooled", k), [])])
                    for _, key in pooled_cols
                ],
            ]
            for k in ks
        ],
    )
    lines += ["", "## Collateral: pooled test split recall per class", ""]
    classes = ["black_rust", "brown_rust", "healthy", "septoria", "yellow_rust"]
    lines += table(
        ["k", *[f"`{c}`" for c in classes], "macro-F1"],
        [
            [
                k,
                *[
                    _cell([r.get(f"pooled_recall_{c}") for r in results.get(("pooled", k), [])])
                    for c in classes
                ],
                _cell([r.get("pooled_test_macro_f1") for r in results.get(("pooled", k), [])]),
            ]
            for k in ks
        ],
    )
    lines += [
        "",
        f"## Transfer: LOSO model without `{cfg.controls.transfer_fold}`, adapted on NWRD",
        "",
    ]
    present = [
        c
        for c in classes
        if any(f"ethiopia_recall_{c}" in r for rs in results.values() for r in rs)
    ]
    t_cols = [
        ("NWRD rust recall", "nwrd_test_recall"),
        *[(f"Ethiopia `{c}`", f"ethiopia_recall_{c}") for c in present],
        ("Ethiopia healthy → disease", "ethiopia_healthy_called_disease"),
    ]
    lines += table(
        ["k", "draws", *[n for n, _ in t_cols]],
        [
            [
                k,
                len(results.get(("transfer", k), [])),
                *[
                    _cell([r.get(key) for r in results.get(("transfer", k), [])])
                    for _, key in t_cols
                ],
            ]
            for k in ks
        ],
    )
    lines += ["", "## Where pooled-test images go: share of each class predicted `yellow_rust`", ""]
    others = [c for c in classes if c != YELLOW]
    lines += table(
        ["k", *[f"`{c}` → yellow" for c in others]],
        [
            [
                k,
                *[
                    _cell([r.get(f"pooled_as_yellow_{c}") for r in results.get(("pooled", k), [])])
                    for c in others
                ],
            ]
            for k in ks
        ],
    )
    lines += [
        "",
        "## Adapt-split selection score (picks the model to keep; test split not used)",
        "",
    ]
    lines += table(
        ["k", "draw", "adapt recall (undrawn tiles)", "val healthy → yellow", "score"],
        [
            [
                k,
                d,
                f"{r['select_adapt_recall']:.3f}",
                f"{r['select_val_healthy_fpr']:.3f}",
                f"{r['select_score']:.3f}",
            ]
            for k in cfg.select.ks
            for d, r in enumerate(results.get(("pooled", k), []))
        ],
    )
    return lines


def write_report(cfg) -> Path:
    doc = Path(cfg.output.doc)
    text = doc.read_text(encoding="utf-8") if doc.exists() else f"{INTRO}{START}\n{END}\n"
    doc.write_text(replace_section(text, render(cfg, load_results(cfg))), encoding="utf-8")
    return doc


def main(argv=None) -> None:
    from omegaconf import OmegaConf

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/vision/wheat_v2_fewshot_controls.yaml")
    parser.add_argument("--report-only", action="store_true")
    args = parser.parse_args(argv)
    cfg = OmegaConf.load(args.config)
    if not args.report_only:
        run_controls(cfg, get_logger(__name__))
    print(write_report(cfg))


if __name__ == "__main__":
    main()
