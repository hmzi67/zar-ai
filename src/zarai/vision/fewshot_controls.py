def recall_by_class(logits, labels, classes) -> dict[str, float]:
    preds = logits.argmax(axis=1)
    return {
        c: float((preds[labels == i] == i).mean())
        for i, c in enumerate(classes)
        if (labels == i).any()
    }


def cam_scores(model, loader, yellow: int, masks, device) -> dict[str, float]:
    """Mean Grad-CAM mass inside the rust mask, the mask's area, their ratio, and how often the
    CAM's peak falls on rust."""
    from zarai.vision.gradcam import cam_mass_on_mask, grad_cam

    inside, area, lift, peak = [], [], [], []
    position = 0
    for images, _ in loader:
        cams = grad_cam(model, images, device, target=yellow)[0]
        for cam in cams:
            mask = masks[position]
            position += 1
            if not mask.any():
                continue
            share = cam_mass_on_mask(cam, mask)
            inside.append(share)
            area.append(mask.mean())
            lift.append(share / mask.mean())
            peak.append(bool(mask.flat[cam.argmax()]))
    return {
        "cam_mass_in_rust": float(np.mean(inside)),
        "cam_rust_area": float(np.mean(area)),
        "cam_lift": float(np.mean(lift)),
        "cam_peak_on_rust": float(np.mean(peak)),
    }


def score_pooled(model, loaders, masks, classes, device) -> dict[str, float]:
    from sklearn.metrics import f1_score

    from zarai.vision.train import predict

    yellow, healthy = classes.index(YELLOW), classes.index(HEALTHY)
    preds = {
        name: predict(model, loader, device)[0].argmax(axis=1)
        for name, loader in loaders.items()
        if name != "pooled_test"
    }
    logits, labels = predict(model, loaders["pooled_test"], device)
    metrics = {
        "nwrd_test_recall": float((preds["nwrd_rust"] == yellow).mean()),
        "nwrd_ablated_recall": float((preds["nwrd_ablated"] == yellow).mean()),
        "empty_leaf_yellow": float((preds["nwrd_empty"] == yellow).mean()),
        "empty_leaf_healthy": float((preds["nwrd_empty"] == healthy).mean()),
        "select_adapt_recall": float((preds["adapt_rest"] == yellow).mean()),
        "select_val_healthy_fpr": float((preds["val_healthy"] == yellow).mean()),
        "pooled_test_macro_f1": float(
            f1_score(
                labels, logits.argmax(axis=1), average="macro", labels=list(range(len(classes)))
            )
        ),
        **{f"pooled_recall_{c}": v for c, v in recall_by_class(logits, labels, classes).items()},
        **{
            f"pooled_as_yellow_{c}": float((logits.argmax(axis=1)[labels == i] == yellow).mean())
            for i, c in enumerate(classes)
            if (labels == i).any() and c != YELLOW
        },
    }
    metrics["select_score"] = metrics["select_adapt_recall"] - metrics["select_val_healthy_fpr"]
    metrics.update(cam_scores(model, loaders["nwrd_rust"], yellow, masks, device))
    return metrics


def score_transfer(model, loaders, classes, device) -> dict[str, float]:
    from zarai.vision.train import predict

    yellow, healthy = classes.index(YELLOW), classes.index(HEALTHY)
    logits, labels = predict(model, loaders["ethiopia"], device)
    preds = logits.argmax(axis=1)
    metrics = {
        f"ethiopia_recall_{c}": v for c, v in recall_by_class(logits, labels, classes).items()
    }
    if (labels == healthy).any():
        metrics["ethiopia_healthy_called_disease"] = float(
            (preds[labels == healthy] != healthy).mean()
        )
    metrics["nwrd_test_recall"] = float(
        (predict(model, loaders["nwrd_rust"], device)[0].argmax(axis=1) == yellow).mean()
    )
    return metrics


