# Models


def best_pooled_run(training_cfg, backbone: str, mode: str, aug: str):
    """The finished pooled run of this configuration with the highest val macro-F1."""
    from zarai.vision.results_v2 import load_runs

    splits_md5 = dvc_hashes(training_cfg.data.splits_csv)["dvc.splits_md5"]
    runs = [
        r
        for r in load_runs(training_cfg, splits_md5)
        if r.data.tags.get("protocol") == "pooled"
        and (r.data.tags["backbone"], r.data.tags["mode"], r.data.tags["aug"])
        == (backbone, mode, aug)
        and r.data.tags.get("background", "none") == "none"
    ]
    if not runs:
        raise ValueError(f"no pooled run of {backbone}/{mode}/{aug}: run the pooled training first")
    return max(runs, key=lambda r: r.data.metrics["best_val_macro_f1"])


def load_run_model(run_id: str, device: str):
    """Rebuild a wheat_v2 run's best checkpoint. Returns (model, checkpoint, run config)."""
    import torch

    from zarai.vision import backbones
    from zarai.vision.tracking import artifact_path

    checkpoint = torch.load(
        artifact_path(run_id, "checkpoints/best.pt"), map_location="cpu", weights_only=True
    )
    cfg = OmegaConf.create(checkpoint["config"])
    # linear and lora checkpoints hold only the trained tensors, on top of the pinned weights.
    model = backbones.build(
        cfg, len(checkpoint["classes"]), pretrained=checkpoint["trainable_only"]
    )
    backbones.load_state(model, checkpoint["state_dict"], checkpoint["mode"])
    return model.to(device), checkpoint, cfg


def adapt(model, cfg, run_cfg, rows, classes, mean, std, device, seed: int) -> None:
    """Fine-tune in place for a fixed number of steps on a balanced set."""
    import torch
    from torch.utils.data import DataLoader

    from zarai.vision import backbones
    from zarai.vision.train import set_train_mode
    from zarai.vision.transforms import build_train_transforms

    mode = run_cfg.model.mode
    a = cfg.adapt
    transform = build_train_transforms(
        a.aug, run_cfg.data.image_size, mean, std, run_cfg.train.augment
    )
    batch = min(a.batch_size, len(rows))
    generator = torch.Generator().manual_seed(seed)
    order = torch.randint(len(rows), (a.steps * batch,), generator=generator).tolist()
    loader = DataLoader(
        RowsDataset(rows, classes, transform),
        batch_size=batch,
        sampler=order,
        num_workers=a.num_workers,
        pin_memory=True,
    )
    tuned = copy.deepcopy(run_cfg)
    tuned.train.lr = a.lr[mode]
    tuned.train.weight_decay = a.weight_decay
    optimizer = torch.optim.AdamW(
        backbones.param_groups(model, tuned), lr=a.lr[mode], weight_decay=a.weight_decay
    )
    criterion = torch.nn.CrossEntropyLoss(label_smoothing=a.label_smoothing)
    set_train_mode(model, mode == "linear")
    torch.manual_seed(seed)
    for images, targets in loader:
        with torch.autocast(device_type=device, dtype=torch.bfloat16):
            loss = criterion(model(images.to(device)), targets.to(device))
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()


def score(model, loaders, classes, device) -> dict[str, float]:
    from zarai.vision.train import predict

    yellow, healthy = classes.index(YELLOW), classes.index(HEALTHY)
    tiles = predict(model, loaders["test_yellow"], device)[0].argmax(axis=1)
    leaves = predict(model, loaders["test_healthy"], device)[0].argmax(axis=1)
    return {
        "nwrd_test_recall": float((tiles == yellow).mean()),
        "healthy_fpr_yellow": float((leaves == yellow).mean()),
        "healthy_fpr_any_disease": float((leaves != healthy).mean()),
        "n_nwrd_test": float(len(tiles)),
        "n_healthy_test": float(len(leaves)),
    }


