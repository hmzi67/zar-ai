"""Few-shot adaptation of pooled wheat_v2 models to NWRD stripe rust.

NWRD images (not tiles) are split into adapt and test. For each k, a model's best pooled
checkpoint (highest val macro-F1) is fine-tuned on k yellow_rust tiles from the adapt images plus
k healthy images from the pooled train split of the other sources, for a fixed budget of steps.
It is then scored on:
- NWRD test recall: the share of tiles from the test images predicted yellow_rust;
- false-positive rate: the share of the pooled test split's healthy images (no model trained or
  adapted on them) predicted yellow_rust, and the share predicted as any disease.
k = 0 is the checkpoint unchanged. Every k > 0 has several random draws, the same for every model.
Each adaptation is one MLflow run; the report and plot are built from MLflow.
"""

import argparse
import copy
from collections import defaultdict
from pathlib import Path

import numpy as np
from omegaconf import OmegaConf

from zarai.common.io import read_csv
from zarai.common.logging import get_logger
from zarai.vision.results import END, START, TBD, replace_section, table
from zarai.vision.tracking import dvc_hashes, set_tracking_uri

YELLOW, HEALTHY = "yellow_rust", "healthy"
INTRO = """# wheat_v2 few-shot adaptation to NWRD

Can a few labelled field tiles fix stripe rust on NWRD, and what does it cost on healthy leaves?
Generated by `python -m zarai.vision.fewshot_nwrd` from the MLflow experiment
`wheat_v2_fewshot_nwrd` (`scripts/run_wheat_v2_fewshot.sh` runs everything). Only logged numbers;
[TBD] means not run. Don't edit between the markers.

"""


# ---------------------------------------------------------------------------------------------
# Data


def nwrd_image_id(row: dict) -> str:
    """NWRD tiles are saved as <image stem>_<left>_<top>.png."""
    return Path(row["original_path"]).stem.rsplit("_", 2)[0]


def split_nwrd_images(rows: list[dict], adapt_share: float, seed: int) -> dict[str, str]:
    """{image id: "adapt" | "test"}. Images that share a near-duplicate cluster go together.

    Groups are taken in a seeded random order, and go to adapt until it holds adapt_share of the
    tiles; the rest are test.
    """
    groups: dict[str, set[str]] = defaultdict(set)  # cluster -> image ids
    for row in rows:
        groups[row["cluster_id"]].add(nwrd_image_id(row))
    parent = {}  # union of images linked through clusters

    def find(x):
        while parent.setdefault(x, x) != x:
            x = parent[x]
        return x

    for images in groups.values():
        first, *rest = sorted(images)
        for other in rest:
            parent[find(other)] = find(first)
    tiles_per_group = defaultdict(int)
    members = defaultdict(set)
    for row in rows:
        root = find(nwrd_image_id(row))
        tiles_per_group[root] += 1
        members[root].add(nwrd_image_id(row))
    order = sorted(tiles_per_group)
    np.random.default_rng(seed).shuffle(order)
    side, adapt_tiles, target = {}, 0, adapt_share * len(rows)
    for root in order:
        to_adapt = adapt_tiles < target
        adapt_tiles += tiles_per_group[root] if to_adapt else 0
        for image in members[root]:
            side[image] = "adapt" if to_adapt else "test"
    return side


def adaptation_sets(splits_csv, nwrd_cfg) -> dict[str, list[dict]]:
    """adapt_yellow and test_yellow (NWRD tiles), adapt_healthy (pooled train healthy images from
    the training sources) and test_healthy (pooled test healthy images)."""
    rows = read_csv(splits_csv)
    nwrd = [r for r in rows if r["source"] == "nwrd"]
    side = split_nwrd_images(nwrd, nwrd_cfg.adapt_share, nwrd_cfg.split_seed)
    healthy = [r for r in rows if r["label"] == HEALTHY and r["source"] != "nwrd"]
    return {
        "adapt_yellow": [r for r in nwrd if side[nwrd_image_id(r)] == "adapt"],
        "test_yellow": [r for r in nwrd if side[nwrd_image_id(r)] == "test"],
        "adapt_healthy": [r for r in healthy if r["split_pooled"] == "train"],
        "test_healthy": [r for r in healthy if r["split_pooled"] == "test"],
    }


def draw(sets: dict, k: int, index: int) -> list[dict]:
    """k yellow_rust tiles and k healthy images, without replacement. Seeded by (k, index) only,
    so every model gets the same draws."""
    rng = np.random.default_rng(1000 * k + index)
    yellow = rng.choice(len(sets["adapt_yellow"]), size=k, replace=False)
    healthy = rng.choice(len(sets["adapt_healthy"]), size=k, replace=False)
    return [sets["adapt_yellow"][i] for i in sorted(yellow)] + [
        sets["adapt_healthy"][i] for i in sorted(healthy)
    ]


class RowsDataset:
    """(image, class index) for a list of split CSV rows."""

    def __init__(self, rows, classes, transform):
        self.rows, self.transform = rows, transform
        self.labels = [classes.index(r["label"]) for r in rows]

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, index):
        from PIL import Image

        with Image.open(self.rows[index]["path"]) as image:
            image = image.convert("RGB")
        return self.transform(image), self.labels[index]


