def run_experiment(cfg, log, only: list[str] | None = None) -> None:
    import mlflow
    import torch
    from torch.utils.data import DataLoader

    from zarai.common.config import load_config
    from zarai.vision import backbones
    from zarai.vision.transforms import build_transforms

    training_cfg = load_config(cfg.training_config)
    sets = adaptation_sets(training_cfg.data.splits_csv, cfg.nwrd)
    if max(cfg.ks) > min(len(sets["adapt_yellow"]), len(sets["adapt_healthy"])):
        raise ValueError(
            f"k up to {max(cfg.ks)} needs that many adapt tiles: {len(sets['adapt_yellow'])}"
        )
    log.info(
        "NWRD adapt %d tiles, test %d tiles; healthy adapt pool %d, test %d",
        *(len(sets[k]) for k in ("adapt_yellow", "test_yellow", "adapt_healthy", "test_healthy")),
    )
    splits_md5 = dvc_hashes(training_cfg.data.splits_csv)["dvc.splits_md5"]
    set_tracking_uri(cfg.mlflow.tracking_uri)
    mlflow.set_experiment(cfg.mlflow.experiment)
    device = "cuda"
    for entry in cfg.pooled.configs:
        name = f"{entry.backbone}/{entry.mode}/{entry.aug}"
        if only and name not in only:
            continue
        source = best_pooled_run(training_cfg, entry.backbone, entry.mode, entry.aug)
        model, checkpoint, run_cfg = load_run_model(source.info.run_id, device)
        classes, mean, std = checkpoint["classes"], checkpoint["mean"], checkpoint["std"]
        base_state = backbones.checkpoint_state(model, run_cfg.model.mode)
        eval_transform = build_transforms(
            run_cfg.data.image_size,
            train=False,
            mean=mean,
            std=std,
            eval_resize=run_cfg.data.eval_resize,
        )
        loaders = {
            split: DataLoader(
                RowsDataset(sets[split], classes, eval_transform),
                batch_size=cfg.adapt.eval_batch_size,
                num_workers=cfg.adapt.num_workers,
            )
            for split in ("test_yellow", "test_healthy")
        }
        log.info("%s: pooled run %s (seed %s)", name, source.info.run_id, source.data.tags["seed"])
        for k in cfg.ks:
            for index in range(cfg.draws if k else 1):
                backbones.load_state(model, base_state, run_cfg.model.mode)
                if k:
                    rows = draw(sets, k, index)
                    adapt(
                        model, cfg, run_cfg, rows, classes, mean, std, device, seed=1000 * k + index
                    )
                metrics = score(model, loaders, classes, device)
                with mlflow.start_run(
                    run_name=f"{entry.backbone}_{entry.mode}_{entry.aug}_k{k}_d{index}"
                ):
                    mlflow.set_tags(
                        {
                            "model": name,
                            "k": str(k),
                            "draw": str(index),
                            "source_run_id": source.info.run_id,
                            "source_seed": source.data.tags["seed"],
                        }
                    )
                    mlflow.log_params(
                        {
                            "dvc.splits_md5": splits_md5,
                            **{
                                f"adapt.{key}": value
                                for key, value in OmegaConf.to_container(cfg.adapt).items()
                            },
                            "nwrd.adapt_share": cfg.nwrd.adapt_share,
                            "nwrd.split_seed": cfg.nwrd.split_seed,
                        }
                    )
                    mlflow.log_metrics(metrics)
                log.info(
                    "%s k=%d draw %d: %s",
                    name,
                    k,
                    index,
                    {m: round(v, 4) for m, v in metrics.items()},
                )
        del model
        torch.cuda.empty_cache()


def load_results(cfg) -> dict[tuple[str, int], list[dict]]:
    """{(model, k): [metrics per draw]}, latest run per draw, on the current dataset version."""
    import mlflow

    from zarai.common.config import load_config

    splits_md5 = dvc_hashes(load_config(cfg.training_config).data.splits_csv)["dvc.splits_md5"]
    set_tracking_uri(cfg.mlflow.tracking_uri)
    if mlflow.get_experiment_by_name(cfg.mlflow.experiment) is None:
        return {}
    runs = mlflow.search_runs(
        experiment_names=[cfg.mlflow.experiment],
        output_format="list",
        filter_string="attributes.status = 'FINISHED'",
        order_by=["attributes.start_time ASC"],
    )
    latest = {}
    for run in runs:
        if run.data.params.get("dvc.splits_md5") != splits_md5:
            continue
        t = run.data.tags
        latest[t["model"], int(t["k"]), t["draw"]] = run.data.metrics
    grouped = defaultdict(list)
    for (model, k, _), metrics in sorted(latest.items()):
        grouped[model, k].append(metrics)
    return grouped


def _cell(values: list[float], digits: int = 3) -> str:
    if not values:
        return TBD
    if len(values) == 1:
        return f"{values[0]:.{digits}f}"
    return f"{np.mean(values):.{digits}f} ± {np.std(values, ddof=1):.{digits}f}"


def render(cfg, grouped, sizes: dict[str, int]) -> list[str]:
    models = [f"{c.backbone}/{c.mode}/{c.aug}" for c in cfg.pooled.configs]
    lines = [
        f"NWRD split by image (seed {cfg.nwrd.split_seed}): {sizes['adapt_yellow']} adapt tiles, "
        f"{sizes['test_yellow']} test tiles. Healthy: {sizes['adapt_healthy']} pooled-train images "
        f"to draw from, {sizes['test_healthy']} pooled-test images for the false-positive rate. "
        f"{cfg.adapt.steps} steps per adaptation, batch min({cfg.adapt.batch_size}, 2k), learning "
        f"rate {cfg.adapt.lr.full} (full) or {cfg.adapt.lr.linear} (linear), no early stopping. "
        f"k = 0 is the pooled checkpoint unchanged; other k are mean ± SD over {cfg.draws} draws.",
        "",
        "*Recall*: NWRD test tiles predicted `yellow_rust`. *FPR yellow*: held-out healthy images "
        "predicted `yellow_rust`. *FPR any*: held-out healthy images predicted as any disease.",
        "",
    ]
    rows = []
    for model in models:
        for k in cfg.ks:
            found = grouped.get((model, k), [])
            rows.append(
                [
                    model,
                    k,
                    f"{len(found)}/{cfg.draws if k else 1}",
                    _cell([m["nwrd_test_recall"] for m in found]),
                    _cell([m["healthy_fpr_yellow"] for m in found]),
                    _cell([m["healthy_fpr_any_disease"] for m in found]),
                ]
            )
    lines += table(["model", "k", "draws", "NWRD test recall", "FPR yellow", "FPR any"], rows)
    lines += ["", f"![NWRD test recall against k]({Path(cfg.output.plot).name})", ""]
    return lines


def plot(cfg, grouped, path: Path) -> Path | None:
    from zarai.vision.plots import _pyplot

    plt = _pyplot()
    fig, ax = plt.subplots(figsize=(6.5, 4.5))
    drawn = False
    for entry in cfg.pooled.configs:
        model = f"{entry.backbone}/{entry.mode}/{entry.aug}"
        ks = [k for k in cfg.ks if grouped.get((model, k))]
        if not ks:
            continue
        values = [[m["nwrd_test_recall"] for m in grouped[model, k]] for k in ks]
        sds = [np.std(v, ddof=1) if len(v) > 1 else 0 for v in values]
        ax.errorbar(ks, [np.mean(v) for v in values], yerr=sds, marker="o", capsize=3, label=model)
        drawn = True
    if not drawn:
        plt.close(fig)
        return None
    ax.set(
        xlabel="k (yellow_rust tiles from NWRD adapt images)",
        ylabel="NWRD test recall",
        ylim=(0, 1.02),
    )
    ax.set_xticks(list(cfg.ks))
    ax.legend(loc="best", fontsize=8)
    ax.set_title("Few-shot adaptation to NWRD (mean ± SD over draws)")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def write_report(cfg) -> Path:
    from zarai.common.config import load_config

    training_cfg = load_config(cfg.training_config)
    sets = adaptation_sets(training_cfg.data.splits_csv, cfg.nwrd)
    grouped = load_results(cfg)
    plot(cfg, grouped, Path(cfg.output.plot))
    doc = Path(cfg.output.doc)
    text = doc.read_text(encoding="utf-8") if doc.exists() else f"{INTRO}{START}\n{END}\n"
    lines = render(cfg, grouped, {k: len(v) for k, v in sets.items()})
    doc.write_text(replace_section(text, lines), encoding="utf-8")
    return doc


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/vision/wheat_v2_fewshot.yaml")
    parser.add_argument("--only", nargs="*", help="model names like dinov2_vit_b14/full/strong")
    parser.add_argument("--report-only", action="store_true")
    args = parser.parse_args(argv)
    cfg = OmegaConf.load(args.config)
    log = get_logger(__name__)
    if not args.report_only:
        run_experiment(cfg, log, args.only)
    print(write_report(cfg))


if __name__ == "__main__":
    main()
